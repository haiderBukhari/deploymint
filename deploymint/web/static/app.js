const STEP_ICONS = { running: "●", done: "✓", blocked: "✕", error: "✕" };

function setNodeState(node, state, ms) {
  const li = document.querySelector(`#timeline li[data-node="${node}"]`);
  if (!li) return;
  li.classList.remove("running", "done", "blocked", "error");
  li.classList.add(state);
  const icon = li.querySelector(".step-icon");
  const originalNumber = icon.dataset.number || icon.textContent;
  icon.dataset.number = originalNumber;
  icon.textContent = STEP_ICONS[state] || originalNumber;
  if (ms != null) {
    const time = li.querySelector(".step-time");
    if (time) time.textContent = `${(ms / 1000).toFixed(1)}s`;
  }
}

function setStepDetail(node, text) {
  const li = document.querySelector(`#timeline li[data-node="${node}"]`);
  if (!li) return;
  const detail = li.querySelector(".step-detail");
  if (!detail) return;
  detail.textContent = text;
  detail.classList.add("visible");
}

function appendStepDetail(node, line) {
  const li = document.querySelector(`#timeline li[data-node="${node}"]`);
  if (!li) return;
  const detail = li.querySelector(".step-detail");
  if (!detail) return;
  detail.textContent = detail.textContent ? `${detail.textContent}\n${line}` : line;
  detail.classList.add("visible");
}

function addFinding(f) {
  const list = document.getElementById("findings");
  if (!list) return;
  const li = document.createElement("li");
  li.className = `sev-${f.severity}`;
  li.textContent = `${f.severity} · ${f.id} · ${f.message}`;
  if (f.explanation) {
    const div = document.createElement("div");
    div.className = "explanation";
    div.textContent = f.explanation;
    li.appendChild(div);
  }
  list.appendChild(li);
}

function setStatus(status) {
  const badge = document.getElementById("run-status");
  if (!badge) return;
  badge.textContent = status;
  badge.className = `status status-${status}`;
}

function connectRun(runId, since, initialStatus) {
  // If the run was ALREADY finished when this page loaded, the server-rendered
  // HTML already has the final artifacts/security/cost — the WS replay below
  // will re-deliver a persisted run.end event too, but reloading in response
  // to THAT would reload forever (each reload reconnects, replays run.end
  // again, reloads again...). Only reload for a run.end that arrives while
  // watching live, i.e. the run was still in progress on page load.
  const TERMINAL = ["success", "failed", "blocked", "cancelled"];
  const wasAlreadyTerminal = TERMINAL.includes(initialStatus);

  const proto = location.protocol === "https:" ? "wss" : "ws";
  const ws = new WebSocket(`${proto}://${location.host}/ws/runs/${runId}`);

  ws.onopen = () => ws.send(JSON.stringify({ since }));

  const term = document.getElementById("terminal");
  let buffer = [];
  function flushTerminal() {
    if (!term || !buffer.length) return;
    term.insertAdjacentText("beforeend", buffer.join("\n") + "\n");
    term.scrollTop = term.scrollHeight;
    buffer = [];
  }
  const flush = setInterval(flushTerminal, 100);

  ws.onmessage = (e) => {
    const evt = JSON.parse(e.data);
    since = evt.seq;
    const payload = evt.payload || {};
    switch (evt.type) {
      case "node.enter":
        setNodeState(payload.node, "running");
        break;
      case "node.exit":
        setNodeState(payload.node, "done", payload.ms);
        break;
      case "architect.done":
        setStepDetail("architect",
          `${payload.language || "?"} / ${payload.framework || "?"} · ${payload.file_count} files · entrypoint ${payload.entrypoint || "?"}`);
        break;
      case "smith.done":
        setStepDetail("smith",
          `generated by ${payload.generated_by}${payload.files ? " · " + payload.files.length + " files" : ""}`);
        break;
      case "warden.done": {
        const verdict = payload.passed ? "PASSED" : "BLOCKED";
        setStepDetail("warden",
          `${payload.critical || 0} critical · ${payload.high || 0} high · ${payload.medium || 0} medium · ${verdict}`);
        break;
      }
      case "redteam.done":
        setStepDetail("redteam", `${payload.findings_count} finding(s)`);
        break;
      case "execution.stage":
        setStepDetail("execution", `stage: ${payload.stage}`);
        break;
      case "execution.done":
        setStepDetail("execution",
          `mode: ${payload.mode}${payload.local_url ? " · " + payload.local_url : ""}${payload.pod_name ? " · pod " + payload.pod_name : ""}`);
        break;
      case "oracle.metric":
        setStepDetail("oracle",
          `watching — restarts: ${payload.restarts}, ready: ${payload.ready}`);
        break;
      case "oracle.anomaly":
        setStepDetail("oracle", `⚠ anomaly: ${payload.reason} — rolling back`);
        break;
      case "oracle.done":
        setStepDetail("oracle", payload.samples
          ? `healthy after ${payload.samples} sample(s)`
          : "no pod metrics to watch (docker-run mode)");
        break;
      case "finops.done":
        setStepDetail("finops",
          `$${(payload.monthly_usd || 0).toFixed(2)}/month estimated (${payload.source})`);
        break;
      case "execution.log":
        buffer.push(payload.line);
        break;
      case "warden.finding":
        // If the run was already finished on page load, run.security.findings
        // is already server-rendered from the DB — appending these replayed
        // events on top would duplicate every finding. Only append live.
        if (!wasAlreadyTerminal && payload.id) addFinding(payload);
        break;
      case "redteam.probe":
        // Unlike warden.finding, a probe payload has no id/severity/message —
        // just probe_name/result — so it was never rendering via addFinding()
        // (that check required payload.id, which this event never has).
        appendStepDetail("redteam", `probe hit: ${payload.probe_name}`);
        break;
      case "error":
        // A generic failure from any agent (execution.py explicitly, or any
        // agent via graph.py's exception wrapper). Surface it on the failing
        // step AND in the terminal — a build that fails before producing any
        // stdout would otherwise leave the terminal looking inertly blank
        // with no explanation anywhere on the page.
        if (payload.node) appendStepDetail(payload.node, `⚠ ${payload.message}`);
        buffer.push(`[error] ${payload.message}`);
        break;
      case "run.end":
        // Flush any buffered terminal lines BEFORE clearing the interval.
        // On an already-finished run, the entire replay (every persisted
        // event, execution.log included) arrives essentially instantly —
        // run.end can land well within the first 100ms flush tick, so
        // without this, clearInterval below discards every buffered line
        // and the terminal renders permanently blank despite the real
        // build/deploy output having been sent correctly over the socket.
        flushTerminal();
        setStatus(payload.status);
        clearInterval(flush);
        ws.close();
        // The Artifacts/Security/Cost panels are server-rendered from the DB
        // at page load and are not patched incrementally over the socket —
        // reload once so they pick up the run's final artifacts/security/cost.
        // Only do this the first time (the run was still in progress when
        // this page loaded) — a replay of an already-finished run's events
        // re-delivers this same persisted run.end, and reloading in response
        // to that would loop forever (reload -> replay -> run.end -> reload).
        if (!wasAlreadyTerminal) {
          setTimeout(() => location.reload(), 400);
        }
        break;
    }
  };

  ws.onclose = () => {
    // Reconnect unless the run was already finished (either on page load or
    // just now, live).
    const badge = document.getElementById("run-status");
    const currentlyTerminal = badge && TERMINAL.includes(badge.textContent.trim());
    if (!wasAlreadyTerminal && !currentlyTerminal) {
      setTimeout(() => connectRun(runId, since, initialStatus), 2000);
    }
  };
}

function renderDepGraph(retriesLeft) {
  if (retriesLeft === undefined) retriesLeft = 20;
  const el = document.getElementById("depgraph");
  if (!el) return;

  // cytoscape.min.js is a plain blocking <script src>, so `cytoscape` itself
  // is reliably defined by the time this runs. What isn't reliable is the
  // CONTAINER's layout: if this fires before the page's CSS/box layout has
  // settled, the container can measure 0-width, cytoscape initializes into
  // that zero-size canvas, and — because it never re-measures on its own —
  // the graph silently never appears, with no error anywhere. Retry briefly
  // until the container actually has real dimensions.
  if (typeof cytoscape === "undefined" || el.getBoundingClientRect().width === 0) {
    if (retriesLeft > 0) {
      requestAnimationFrame(() => renderDepGraph(retriesLeft - 1));
    }
    return;
  }

  let graph, critical;
  try {
    graph = JSON.parse(el.dataset.graph || "{}");
    critical = new Set(JSON.parse(el.dataset.critical || "[]"));
  } catch {
    return;
  }
  const nodes = (graph.nodes || []).map((n) => ({
    data: { id: n.id }, classes: critical.has(n.id) ? "critical" : "",
  }));
  const edges = (graph.links || []).map((l, i) => ({
    data: { id: `e${i}`, source: l.source, target: l.target },
  }));
  const cy = cytoscape({
    container: el,
    elements: [...nodes, ...edges],
    style: [
      { selector: "node", style: { label: "data(id)", "font-size": 10,
        "background-color": "#0f9d70", color: "#1f2328", "text-valign": "bottom",
        "text-margin-y": 4 } },
      { selector: "node.critical", style: {
        "background-color": "#9a6700", "border-width": 2, "border-color": "#d4a300",
        "font-weight": "bold",
      } },
      { selector: "edge", style: { "line-color": "#d0d7de",
        "target-arrow-color": "#d0d7de", "target-arrow-shape": "triangle",
        "curve-style": "bezier", width: 1.5 } },
    ],
    // animate: false is the actual fix for the graph rendering nothing on
    // first page load. The default 'cose' layout animates node positions
    // over several of its own requestAnimationFrame ticks — on a fresh page
    // load those ticks can get silently starved before they ever paint
    // (verified: cytoscape created correctly-sized canvases, but every pixel
    // stayed transparent — the animation never advanced a single frame).
    // Calling renderDepGraph() again later worked every time, because by
    // then the page was idle and RAF ticks ran normally. animate:false
    // computes final node positions synchronously in one pass instead of
    // relying on that animation ever getting a chance to run.
    layout: { name: "cose", animate: false },
  });
  cy.resize();
  cy.fit();
}

function escapeHtml(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

const DOCKER_INSTRUCTIONS = [
  "FROM", "RUN", "COPY", "ADD", "WORKDIR", "USER", "EXPOSE", "CMD", "ENV",
  "ARG", "LABEL", "ENTRYPOINT", "VOLUME", "HEALTHCHECK", "STOPSIGNAL", "ONBUILD",
];

function highlightDockerfile(text) {
  return escapeHtml(text).split("\n").map((line) => {
    const m = line.match(/^(\s*)([A-Z]+)(\s|$)/);
    if (m && DOCKER_INSTRUCTIONS.includes(m[2])) {
      return `${m[1]}<span class="hl-kw">${m[2]}</span>${line.slice(m[0].length - m[3].length)}`;
    }
    if (line.trim().startsWith("#")) return `<span class="hl-comment">${line}</span>`;
    return line;
  }).join("\n");
}

function highlightYaml(text) {
  return escapeHtml(text).split("\n").map((line) => {
    if (line.trim().startsWith("#")) return `<span class="hl-comment">${line}</span>`;
    const m = line.match(/^(\s*(?:- )?)([\w.-]+)(:)/);
    if (m) {
      return `${m[1]}<span class="hl-key">${m[2]}</span>${m[3]}${line.slice(m[0].length)}`;
    }
    return line;
  }).join("\n");
}

async function wireArtifactTabs(runId) {
  const tabs = document.getElementById("artifact-tabs");
  const preview = document.getElementById("artifact-preview");
  if (!tabs || !preview) return;

  async function load(filename) {
    const r = await fetch(`/api/runs/${runId}/artifacts/${filename}`);
    const text = r.ok ? await r.text() : "(not generated)";
    if (filename.endsWith(".yaml") || filename.endsWith(".yml")) {
      preview.innerHTML = highlightYaml(text);
    } else if (filename === "Dockerfile") {
      preview.innerHTML = highlightDockerfile(text);
    } else {
      // .tf, .json, and anything else: escape only, no keyword highlighting —
      // a small hand-rolled highlighter for two formats is worth it; one for
      // every IaC format DeployMint now generates is not.
      preview.textContent = text;
    }
  }

  tabs.querySelectorAll(".tab").forEach((btn) => {
    btn.addEventListener("click", () => {
      tabs.querySelectorAll(".tab").forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");
      load(btn.dataset.file);
    });
  });

  const first = tabs.querySelector(".tab");
  if (first) load(first.dataset.file);
}

function collectCloudCreds(cloud) {
  if (cloud === "azure") {
    return {
      azure_subscription_id: document.getElementById("cd-az-sub").value,
      azure_tenant_id: document.getElementById("cd-az-tenant").value,
      azure_client_id: document.getElementById("cd-az-client").value,
      azure_client_secret: document.getElementById("cd-az-secret").value,
    };
  }
  if (cloud === "gcp") {
    return {
      gcp_project: document.getElementById("cd-gcp-project").value,
      gcp_credentials_json: document.getElementById("cd-gcp-json").value,
    };
  }
  return {
    aws_access_key_id: document.getElementById("cd-aws-key").value,
    aws_secret_access_key: document.getElementById("cd-aws-secret").value,
    aws_session_token: document.getElementById("cd-aws-token").value,
    aws_region: document.getElementById("cd-aws-region").value,
  };
}

function wireCloudDeploy(runId) {
  const card = document.getElementById("cloud-deploy");
  if (!card) return;
  const cloud = card.dataset.cloud;
  const output = document.getElementById("cloud-deploy-output");
  const planBtn = document.getElementById("cd-plan-btn");
  const applyBtn = document.getElementById("cd-apply-btn");
  const confirmBox = document.getElementById("cd-confirm");

  ["aws", "azure", "gcp"].forEach((c) => {
    const el = document.getElementById(`cloud-creds-${c}`);
    if (el) el.style.display = c === cloud ? "" : "none";
  });

  confirmBox.addEventListener("change", () => {
    applyBtn.disabled = !confirmBox.checked || applyBtn.dataset.planOk !== "1";
  });

  function streamOutput(onEnd) {
    const proto = location.protocol === "https:" ? "wss" : "ws";
    const ws = new WebSocket(`${proto}://${location.host}/ws/deploy/${runId}`);
    ws.onmessage = (ev) => {
      const msg = JSON.parse(ev.data);
      if (msg.type === "cloud.line") {
        output.textContent += (output.textContent ? "\n" : "") + msg.line;
        output.scrollTop = output.scrollHeight;
      } else if (msg.type === "cloud.end") {
        onEnd(msg.status);
      } else if (msg.type === "cloud.error") {
        output.textContent += `\n${msg.line}`;
      }
    };
  }

  async function run(action, btn) {
    output.textContent = "";
    btn.disabled = true;
    const r = await fetch(`/api/runs/${runId}/cloud/${action}`, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify(collectCloudCreds(cloud)),
    });
    if (!r.ok) {
      const body = await r.json().catch(() => ({}));
      output.textContent = `error: ${body.detail || r.statusText}`;
      btn.disabled = false;
      return;
    }
    streamOutput((status) => {
      btn.disabled = false;
      if (action === "plan") {
        applyBtn.dataset.planOk = status === "success" ? "1" : "0";
        applyBtn.disabled = !(status === "success" && confirmBox.checked);
      }
    });
  }

  planBtn.addEventListener("click", () => run("plan", planBtn));
  applyBtn.addEventListener("click", () => {
    if (!confirmBox.checked) return;
    run("apply", applyBtn);
  });
}

function wireFolderPicker() {
  // A browser folder-select input (<input type=file webkitdirectory>) can't
  // give JS the absolute filesystem path of what was picked at all — that's
  // a deliberate browser sandboxing limit, not something a workaround fixes.
  // So the picker is server-driven instead: dashboard.html renders a
  // <select> from core.sandbox.list_workspace_dirs() (real folders actually
  // present under ./projects), and this just auto-fills the name field from
  // whichever one gets picked — one less thing to type, not a required step.
  const select = document.getElementById("folder-select");
  const nameInput = document.getElementById("name-input");
  if (!select || !nameInput) return;

  select.addEventListener("change", () => {
    if (nameInput.value.trim()) return; // don't clobber a name the user already typed
    const opt = select.options[select.selectedIndex];
    const folder = opt && opt.dataset.name;
    if (!folder) return;
    nameInput.value = folder.toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "");
  });
}

function wireCostForm() {
  const form = document.getElementById("cost-form");
  if (!form) return;
  form.addEventListener("submit", async (e) => {
    e.preventDefault();
    const question = document.getElementById("cost-question").value;
    const r = await fetch("/api/costs/query", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ question }),
    });
    const body = await r.json();
    document.getElementById("cost-answer").innerHTML = body.answer.replace(
      /\*\*(.+?)\*\*/g, "<strong>$1</strong>"
    );
  });
}
